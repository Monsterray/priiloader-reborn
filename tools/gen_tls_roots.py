#!/usr/bin/env python3
"""Regenerate src/priiloader/tls/source/tls_roots.c from Mozilla's CA bundle.

    python tools/gen_tls_roots.py cacert.pem            # from https://curl.se/ca/cacert.pem (check its .sha256)

Picks the roots listed in ROOTS by name, prints subject, expiry and SHA-256 fingerprint into the C
comments (read from openssl, which must be on PATH or in the devkitPro msys2). Review the diff: the
list is the trust anchors of Priiloader's HTTPS client.
"""
import pathlib
import re
import shutil
import subprocess
import sys

ROOTS = [
    "USERTrust ECC Certification Authority",
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "ISRG Root X1",
    "ISRG Root X2",
]
OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "priiloader" / "tls" / "source" / "tls_roots.c"


def find_openssl():
    for c in (shutil.which("openssl"), r"C:\devkitPro\msys2\usr\bin\openssl.exe"):
        if c and pathlib.Path(c).exists():
            return c
    sys.exit("openssl not found")


def main():
    bundle = pathlib.Path(sys.argv[1]).read_bytes().decode()
    openssl = find_openssl()
    parts = []
    for name in ROOTS:
        m = re.search(r"^" + re.escape(name) + r"\n=+\n(?:.*\n)*?(-----BEGIN CERTIFICATE-----\n[A-Za-z0-9+/=\n]+?-----END CERTIFICATE-----\n)",
                      bundle, re.M)
        if not m:
            sys.exit("not in the bundle: " + name)
        pem = m.group(1)
        info = subprocess.run([openssl, "x509", "-noout", "-subject", "-issuer", "-enddate", "-fingerprint", "-sha256"],
                              input=pem.encode(), capture_output=True, check=True).stdout.decode().splitlines()
        info = {k: v for k, v in (l.split("=", 1) for l in info)}
        assert info["subject"] == info["issuer"], name + " is not self-signed"
        lines = "".join('\t"%s' % l + chr(92) + 'n"\n' for l in pem.splitlines())
        parts.append("/* %s\n * expires %s\n * SHA-256 %s */\n%s" % (name, info["notAfter"], info["sha256 Fingerprint"], lines))
    text = ("/*\n * tls_roots.c: the trust anchors of Priiloader's HTTPS client. GENERATED by tools/gen_tls_roots.py from\n"
            " * Mozilla's CA bundle (curl.se/ca/cacert.pem); do not edit by hand. Why these: src/third_party/mbedtls/VENDORED.md.\n */\n"
            "#include \"tls.h\"\n\nconst char tls_root_pem[] =\n" + "\n".join(parts) + ";\n\n"
            "const size_t tls_root_pem_size = sizeof(tls_root_pem);\n")
    OUT.write_bytes(text.encode())
    print("wrote", OUT)


main()
